# Builds the "no R needed" page: upload a spreadsheet, get the wizard.
#
#   Rscript webr/build.R [output folder]        (default: webr/_site)
#
# The page runs dimoose in the browser with webR (https://docs.r-wasm.org/webr/).
# Installing the whole package there would pull in httr, rvest, xml2 and
# their many dependencies, none of which the spreadsheet-to-wizard path uses.
# So this script bundles only the R files that path needs into one script,
# dimoose-bundle.R, which the page sources; the only packages webR then has
# to install are R6, data.tree (with stringi) and base64enc.
#
# The output folder is self-contained and static:
#   index.html          the page (copied from webr/index.html)
#   dimoose-bundle.R    the R code, the wizard's CSS and JavaScript
#   example/            the Montana spreadsheet, its photos and files.json
#
# After building, the bundle is run under plain R on the Montana example
# (--no-check skips that) so a change in R/ that breaks the page is caught here.

args <- commandArgs(trailingOnly = TRUE)
check <- !"--no-check" %in% args
args <- setdiff(args, "--no-check")

scriptPath <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
webrDir <- if (length(scriptPath)) dirname(normalizePath(scriptPath)) else normalizePath("webr")
root <- dirname(webrDir)
out <- if (length(args)) args[1] else file.path(webrDir, "_site")
dir.create(out, recursive = TRUE, showWarnings = FALSE)
out <- normalizePath(out)

# The R files behind keyFromSpreadsheet() and exportWizard(). import.R is here
# for keyPaths(); its web-scraping functions are never called by the page.
# quality.R is here because printing or summarising a key (dimoose.R) calls
# keyQuality(); its GBIF function is never called by the page.
sources <- c("dimoose.R", "import.R", "export.R", "features.R", "images.R", "keys.R", "spreadsheet.R",
             "quality.R")

# The packages the page installs in webR (PACKAGES in index.html, plus stringi,
# which data.tree needs), and the ones that may get loaded on a developer's
# machine but are not needed: imageMeta() uses magick only if it is there.
webrPackages <- c("R6", "data.tree", "stringi", "base64enc")
localOnly <- c("magick", "Rcpp", "magrittr")

readText <- function(path) readLines(path, warn = FALSE, encoding = "UTF-8")
description <- read.dcf(file.path(root, "DESCRIPTION"))
version <- description[1, "Version"]

# exportWizard() finds the wizard's CSS and JavaScript with system.file() and
# stamps the page with packageVersion("dimoose"). Both work without installing
# the package if a library folder holds a "dimoose" folder with a DESCRIPTION
# file and the wizard files, so the bundle starts by writing one.
stub <- c(
  "local({",
  "  lib <- file.path(tempdir(), \"dimoose-lib\")",
  "  dir.create(file.path(lib, \"dimoose\", \"wizard\"), recursive = TRUE, showWarnings = FALSE)",
  "  put <- function(lines, ...) {",
  "    con <- file(file.path(lib, \"dimoose\", ...), open = \"wb\")",
  "    on.exit(close(con))",
  "    writeBin(charToRaw(enc2utf8(paste0(paste(lines, collapse = \"\\n\"), \"\\n\"))), con)",
  "  }",
  sprintf("  put(c(\"Package: dimoose\", \"Version: %s\"), \"DESCRIPTION\")", version),
  paste0("  put(", paste(deparse(readText(file.path(root, "inst", "wizard", "wizard.css"))), collapse = "\n    "),
         ", \"wizard\", \"wizard.css\")"),
  paste0("  put(", paste(deparse(readText(file.path(root, "inst", "wizard", "wizard.js"))), collapse = "\n    "),
         ", \"wizard\", \"wizard.js\")"),
  "  .libPaths(c(lib, .libPaths()))",
  "})"
)

# What the page calls: read the spreadsheet (photos are looked for next to
# it), write the wizard, and return a short report, one "name: value" per line.
entry <- c(
  "webrWizard <- function(csv, out, title = NA) {",
  "  notes <- character()",
  "  withCallingHandlers({",
  "    key <- keyFromSpreadsheet(csv, desc = title)",
  "    notes <- c(notes, key$validate())",
  "    exportWizard(key, out)",
  "  }, warning = function(w) {",
  "    notes <<- c(notes, conditionMessage(w))",
  "    invokeRestart(\"muffleWarning\")",
  "  })",
  "  leads <- key$leads",
  "  photos <- sum(grepl(\"^image_\", key$meta$key))",
  "  paste(c(",
  "    paste(\"couplets:\", length(unique(leads$Statement))),",
  "    paste(\"results:\", length(unique(leads$Taxon[nzchar(leads$Taxon)]))),",
  "    paste(\"photos:\", photos),",
  "    if (length(notes)) paste(\"note:\", unique(gsub(\"\\n\", \" \", notes)))",
  "  ), collapse = \"\\n\")",
  "}"
)

bundle <- c(
  sprintf("# dimoose %s for the webR page. Generated by webr/build.R from R/ and", version),
  "# inst/wizard/; do not edit by hand.",
  "", stub, ""
)
for (f in sources) {
  bundle <- c(bundle, paste0("# ---- R/", f, " ", strrep("-", 60)), readText(file.path(root, "R", f)), "")
}
bundle <- c(bundle, "# ---- the page's entry point ----", entry)
bundleFile <- file.path(out, "dimoose-bundle.R")
con <- file(bundleFile, open = "wb")
writeBin(charToRaw(enc2utf8(paste0(paste(bundle, collapse = "\n"), "\n"))), con)
close(con)

if (normalizePath(webrDir) != out) {
  invisible(file.copy(file.path(webrDir, "index.html"), file.path(out, "index.html"), overwrite = TRUE))
}

# The Montana example: the spreadsheet and the photos it names
montana <- file.path(root, "inst", "extdata", "montana")
example <- file.path(out, "example")
dir.create(example, showWarnings = FALSE)
files <- c("montana-key.csv", list.files(montana, pattern = "\\.(jpe?g|png|gif|webp)$", ignore.case = TRUE))
invisible(file.copy(file.path(montana, files), example, overwrite = TRUE))
quote <- function(x) paste0("\"", gsub("([\"\\\\])", "\\\\\\1", x), "\"")
writeLines(c(
  "{",
  "  \"title\": \"Native broadleaf trees of Montana\",",
  sprintf("  \"csv\": %s,", quote(files[1])),
  sprintf("  \"photos\": [%s]", paste(quote(files[-1]), collapse = ", ")),
  "}"
), file.path(example, "files.json"))

message(sprintf("Wrote %s (%d KB of R) and %d example files to %s",
                basename(bundleFile), round(file.size(bundleFile) / 1024), length(files), out))

if (check) {
  # Run the bundle the way the page does, in a fresh R that has not loaded
  # dimoose, and make sure it needed none of the packages the page leaves out.
  test <- tempfile(fileext = ".R")
  writeLines(c(
    sprintf("allowed <- %s", paste(deparse(c(webrPackages, localOnly)), collapse = "")),
    sprintf("source(%s, encoding = \"UTF-8\")", deparse(bundleFile)),
    "html <- tempfile(fileext = \".html\")",
    sprintf("report <- webrWizard(%s, html, \"Montana\")", deparse(file.path(example, "montana-key.csv"))),
    "cat(report, \"\\n\")",
    sprintf("shown <- utils::capture.output(print(keyFromSpreadsheet(%s)))", deparse(file.path(example, "montana-key.csv"))),
    "stopifnot(any(grepl(\"couplets\", shown)))",
    "page <- readLines(html, warn = FALSE)",
    "stopifnot(any(grepl(\"<title>Montana</title>\", page, fixed = TRUE)), grepl(\"photos: [1-9]\", report),",
    "          !grepl(\"note:\", report))",
    "allowed <- c(rownames(installed.packages(priority = \"base\")), allowed)",
    "extra <- setdiff(loadedNamespaces(), allowed)",
    "if (length(extra)) stop(\"The bundle loaded packages the page does not install: \", paste(extra, collapse = \", \"))"
  ), test)
  status <- system2(file.path(R.home("bin"), "Rscript"), c("--vanilla", shQuote(test)))
  if (status != 0) {
    stop("The bundle failed on the Montana example; see the messages above.\n",
         "If a function was not found, add the R file that defines it to `sources` in webr/build.R.\n",
         "If a package was loaded, the page has to install it too: add it to PACKAGES in webr/index.html\n",
         "and to `webrPackages` here, after checking that https://repo.r-wasm.org/ has it.", call. = FALSE)
  }
  message("Checked: the bundle builds the Montana wizard under plain R")
}
